const byId = new Map(PROVIDERS.map((p) => [p.id, p]));
const byName = new Map(PROVIDERS.map((p) => [p.name.toLowerCase(), p]));
const byDomain = new Map(PROVIDERS.flatMap((p) => p.domains.map((d) => [d, p])));

/** Resolve a stored provider value (an id, or legacy free text) to a known provider. */
export function providerFor(value) {
  if (!value) return null;
  const v = String(value).trim().toLowerCase();
  return byId.get(v) || byName.get(v) || null;
}

/** Guess the provider from an email address, or null. */
export function detectProvider(address) {
  const domain = String(address || '').split('@')[1];
  return domain ? byDomain.get(domain.trim().toLowerCase()) || null : null;
}
